{
	char mems_head[133];
	char mems_end[133];
	char mems_data[1024];
} MEMS_UP_DATA;

/****************************ARM回复给显控的硬件状态信息SS 共计8字节****************************/
typedef struct
{
	int FPGAVersion;  // FPGA版本号
	int LinuxVersion; // Linux 驱动版本号
} __attribute__((packed)) SEND_UPPER_SONAR_STATUS;

/*************************显控发送给ARM参数配置信息3264字节**********************/
typedef struct
{
	unsigned int TotalBytes;	//总字节数
	int DataType;				   // 数据类型0：表示采样数据，1：表示IQ解调
	int WorkMode;				   // 0:CW,1:LFM
	int LFMMode;				   // 0:升频，1:降频
	int PWMFreq;				   // signal Freq,pwm中心频率
	int PWMBandWidth;			   // PWM带宽CW为0,LFM:波带宽是频率的10%
	int SamplingRate;			   // current K采样率
	int Range;					   // 5m/10m/20m/50m/75m/100m/1250m/150m/200m/240m/300m/400m/500m 共13档
	int ManualGain;				   // 手动增益的值，-40dB 至40dB
	int AbsorbGainCoef;			   // 吸收系数值，0 至50 dB/Km
	int SpreadGainCoef;			   // 扩散系数值，0 至20 dB/Km
	unsigned int tvgGain[TVG_SUM]; // tvgGain[800];//3200
	float PulseWidth;			   // 脉宽us
	float PingRate;				   // 设置的帧率(ping率)
	char PwmStart;				   // PWM开关 1:开  0：关
	char Pitch_stability;		   // 纵摇稳定 1:开  0：关
	// unsigned int SourceChannelC;   // 通道控制字
	float power;				// 功率
	char sync_status;				//同步状态 1外同步 0是内同步
	char Reserved[13];			   // 预留-4
} __attribute__((packed)) RECV_UPPER_CONFIG_PARAMETERS;
